#!/usr/bin/env bash
# Copies pkg/gqlclient from an older reearth-accounts/server version, with the
# domain packages it imports, into oldclient/ under a rewritten import path, so
# the e2e suite can run that client against the current server in one binary.
# Usage: e2e/compat/sync.sh <module version>   (run from server/)
set -euo pipefail

version="$1"
mod="github.com/reearth/reearth-accounts/server"
dest="e2e/compat/oldclient"
src="$(GOFLAGS=-mod=mod go mod download -json "$mod@$version" | sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')"

rm -rf "$dest"
for pkg in gqlclient id role user workspace; do
  (cd "$src/pkg" && find "$pkg" -name '*.go' ! -name '*_test.go' ! -path '*/mockrepo/*') | while read -r f; do
    mkdir -p "$dest/$(dirname "$f")"
    { echo "// Code generated by e2e/compat/sync.sh from $mod@$version. DO NOT EDIT."; echo
      sed -e "s#\"$mod/pkg/#\"$mod/$dest/#g" -e "/^\/\/go:generate/d" "$src/pkg/$f"; } > "$dest/$f"
  done
done
echo "$version" > "$dest/VERSION"
